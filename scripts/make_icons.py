#!/usr/bin/env python3
"""Generate clipcrow/service/static/icons.css (CSS-mask icons) from Lucide and Simple Icons.

Run by a developer, never at runtime or in tests:  python scripts/make_icons.py
Downloads the SVG sources once from raw.githubusercontent.com (pinned tags, TLS verified,
uses HTTPS_PROXY and SSL_CERT_FILE/REQUESTS_CA_BUNDLE from the environment) and inlines them
as data: URIs, because the content-security policy allows no external requests.
See docs/icons.md.
"""
from __future__ import annotations

import re
import ssl
import sys
import urllib.request
from pathlib import Path

LUCIDE_TAG = "0.577.0"
SIMPLE_TAG = "13.0.0"  # last release that still ships linkedin.svg (removed in 14.0.0)
RAW = "https://raw.githubusercontent.com/{repo}/{tag}/icons/{name}.svg"
OUT = Path(__file__).resolve().parent.parent / "clipcrow" / "service" / "static" / "icons.css"

# Rules that live in style.css and must not be emitted here.
SKIP = {"upload", "film"}
# CSS class name -> Lucide file name, where Lucide renamed the file.
LUCIDE_FILE = {"circle-help": "circle-question-mark"}
LUCIDE = """plus list palette badge-check download archive play scissors pencil trash-2 check x
refresh-cw info circle-help sliders-horizontal music volume-2 captions shuffle users mic share-2
send image type clock triangle-alert sparkles link copy eye folder user log-out layers zoom-in
languages gauge file-text rotate-ccw external-link chevron-down chevron-right circle-check
circle-x loader wand-sparkles film upload house settings""".split()
PLATFORMS = """youtube instagram facebook tiktok x linkedin telegram threads pinterest bluesky
reddit whatsapp snapchat mastodon""".split()

HEAD = ("%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' "
        "{attrs}%3E{body}%3C/svg%3E")
LINE_ATTRS = "fill='none' stroke='black' stroke-width='1.8' stroke-linecap='round' stroke-linejoin='round'"
FILL_ATTRS = "fill='black'"
SHAPE = re.compile(r"<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)/?>", re.S)
ATTR = re.compile(r'([\w-]+)\s*=\s*"([^"]*)"')
WS = re.compile(r"\s+")
KEEP = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "x2", "y1", "y2", "width", "height", "points"}


def fetch(repo: str, tag: str, name: str) -> str:
    ctx = ssl.create_default_context()  # honours SSL_CERT_FILE; verification stays on
    url = RAW.format(repo=repo, tag=tag, name=name)
    with urllib.request.urlopen(url, context=ctx, timeout=30) as r:
        return r.read().decode("utf-8")


def shapes(svg: str, name: str) -> str:
    out = []
    for tag, attrs in SHAPE.findall(svg):
        kept = []
        for k, v in ATTR.findall(attrs):
            if k in KEEP:
                kept.append("%s='%s'" % (k, WS.sub(" ", v).strip()))
        out.append("<%s %s/>" % (tag, " ".join(kept)))
    if not out:
        raise SystemExit(f"{name}: no shapes found")
    return "".join(out)


def encode(s: str) -> str:
    return s.replace("%", "%25").replace("#", "%23").replace("<", "%3C").replace(">", "%3E")


def rule(cls: str, attrs: str, body: str) -> str:
    uri = HEAD.format(attrs=attrs, body=encode(body))
    return f'.i-{cls} {{ --m: url("data:image/svg+xml,{uri}"); }}'


def main() -> None:
    rules: dict[str, str] = {}
    for name in LUCIDE:
        if name in SKIP:
            continue
        svg = fetch("lucide-icons/lucide", LUCIDE_TAG, LUCIDE_FILE.get(name, name))
        rules[name] = rule(name, LINE_ATTRS, shapes(svg, name))
    for slug in PLATFORMS:
        svg = fetch("simple-icons/simple-icons", SIMPLE_TAG, slug)
        rules[f"plat-{slug}"] = rule(f"plat-{slug}", FILL_ATTRS, shapes(svg, slug))
    header = (
        "/* GENERATED by scripts/make_icons.py - do not edit by hand. See docs/icons.md.\n"
        f" * Line icons: Lucide {LUCIDE_TAG} (github.com/lucide-icons/lucide), ISC licence.\n"
        f" * Platform logos: Simple Icons {SIMPLE_TAG} (github.com/simple-icons/simple-icons), CC0-1.0\n"
        " *   as drawings; the logos are trademarks of their owners, used only to identify the platform.\n"
        " * Used with the .i class in style.css (mask over currentColor). */\n"
    )
    OUT.write_text(header + "\n".join(rules[k] for k in sorted(rules)) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rules)} icons, {OUT.stat().st_size} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
